"""
Pipeline Shared State — CrediFlow
===================================

Defines ``LoanApplicationState``, the single TypedDict that every agent
in the LangGraph pipeline reads from and writes to.

This maps directly to Section 3 (System Architecture) of the paper:
every field represents a data artifact produced or consumed by one of
the six pipeline nodes.

Design notes
------------
* All fields are ``Optional`` so the graph can start with only the raw
  document bytes and progressively enrich the state as each agent runs.
* ``Annotated[..., operator.add]`` is deliberately **not** used here
  because every agent replaces (not appends) its section of the state.
* ``Sequence`` / ``list`` types are used for multi-valued outputs
  (SHAP values, counterfactuals, loan offers, etc.).

Field groups
------------
    ┌── Intake ──────────────────────────────────────────────────────┐
    │  document_bytes, content_type, raw_ocr_text,                  │
    │  parsed_application, extraction_confidence                     │
    ├── Verification (KYC) ─────────────────────────────────────────┤
    │  kyc_passed, kyc_result                                        │
    ├── Risk Assessment ────────────────────────────────────────────┤
    │  risk_probability, risk_label, risk_calibrated_score,          │
    │  feature_importance, shap_values, counterfactuals              │
    ├── Fraud ──────────────────────────────────────────────────────┤
    │  fraud_score, fraud_flags                                      │
    ├── Negotiation ────────────────────────────────────────────────┤
    │  loan_offers                                                   │
    ├── Audit ──────────────────────────────────────────────────────┤
    │  audit_record                                                  │
    ├── Human Review ───────────────────────────────────────────────┤
    │  human_decision, human_comment                                 │
    ├── AI layer (LLM) ─────────────────────────────────────────────┤
    │  intake_insights, risk_input_features, risk_insights,         │
    │  negotiation_insights, case_summary, llm_trace,               │
    │  kyc_flagged_for_review                                        │
    └── Routing metadata ───────────────────────────────────────────┘
      rejection_reason, needs_human_review, pipeline_status
"""

from __future__ import annotations

from typing import Any, Dict, List, Optional, TypedDict


# ---------------------------------------------------------------------------
# Nested sub-types (for clarity & IDE auto-complete)
# ---------------------------------------------------------------------------

class KYCResult(TypedDict, total=False):
    """Result payload from the Verification (KYC) agent."""
    pan_valid:     bool
    aadhaar_valid: bool
    name_match:    bool
    details:       str
    age_ok:        bool
    warnings:      List[str]
    pan_type:      Optional[str]
    aadhaar_qr:    Dict[str, Any]
    summary:       str                  # LLM (or rule) explanation
    reasons:       List[str]
    concern_level: str                  # "low" | "medium" | "high"
    recommended_action: str             # "proceed" | "manual_review" | "reject"
    applicant_message: str
    explained_by:  str                  # "llm" | "rules"


class FraudFlag(TypedDict, total=False):
    """Single fraud indicator."""
    flag_type:   str      # e.g. "velocity_check", "document_tampering"
    description: str
    severity:    str      # "low" | "medium" | "high"


class LoanOffer(TypedDict, total=False):
    """One possible loan offer generated by the Negotiation agent."""
    interest_rate:       float
    tenor_months:        int
    collateral_required: str     # "None" | "Optional" | "Mandatory"
    decision:            str     # "Pre-Approved" | "Approved with Conditions" | …
    notes:               str


class SHAPExplanation(TypedDict, total=False):
    """Per-feature SHAP value for one prediction."""
    feature: str
    value:   float


class Counterfactual(TypedDict, total=False):
    """One counterfactual scenario from the Risk agent."""
    changed_features: Dict[str, Any]
    new_risk_label:   str
    narrative:        str


# ---------------------------------------------------------------------------
# ━━━  Main shared state  ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
# ---------------------------------------------------------------------------

class LoanApplicationState(TypedDict, total=False):
    """
    The single shared state that flows through the LangGraph pipeline.

    Every agent reads from and writes to this TypedDict.  ``total=False``
    makes every key optional so the graph can be initialised with just the
    raw document bytes.
    """

    # ── Intake Agent ──────────────────────────────────────────────────
    document_bytes:          bytes                # raw uploaded file
    content_type:            str                  # MIME type (e.g. "application/pdf")
    raw_ocr_text:            str                  # full OCR output
    parsed_application:      Dict[str, Any]       # structured fields from OCR
    extraction_confidence:   float                # 0–1 confidence score

    # ── Verification Agent (KYC) ──────────────────────────────────────
    kyc_passed:              bool                 # overall pass / fail
    kyc_result:              KYCResult            # detailed KYC payload

    # ── Fraud Detection ───────────────────────────────────────────────
    fraud_score:             float                # 0–1, higher = more suspicious
    fraud_flags:             List[FraudFlag]      # individual fraud indicators

    # ── Risk Assessment Agent ─────────────────────────────────────────
    risk_probability:        float                # raw default probability
    risk_label:              str                  # "Low" | "Medium" | "High"
    risk_calibrated_score:   float                # Platt-scaled or isotonic score
    feature_importance:      Dict[str, float]     # per-feature Gini / gain importance
    shap_values:             List[SHAPExplanation] # per-feature Shapley explanations
    counterfactuals:         List[Counterfactual] # "what-if" scenarios

    # ── Negotiation Agent ─────────────────────────────────────────────
    loan_offers:             List[LoanOffer]      # one or more offer options

    # ── Audit Agent ───────────────────────────────────────────────────
    audit_record:            Dict[str, Any]       # complete audit trail entry

    # ── Human Review ──────────────────────────────────────────────────
    human_decision:          str                  # "approve" | "reject" | "escalate"
    human_comment:           str                  # free-text reviewer comment

    # ── AI layer (added when the agents became LLM-powered) ───────────
    intake_insights:         Dict[str, Any]       # document type, field sources/confidence, notes
    kyc_flagged_for_review:  bool                 # KYC passed but something looks worrying
    risk_input_features:     Dict[str, Any]       # exact feature vector sent to the ML model
    risk_insights:           Dict[str, Any]       # LLM explanation + limitations + data gaps
    negotiation_insights:    Dict[str, Any]       # rationale, tips, scenarios, guard-rail log
    case_summary:            Dict[str, Any]       # audit memo + consistency checks
    llm_trace:               List[Dict[str, Any]] # one entry per LLM call (model, latency, tokens)

    # ── Pipeline Routing / Meta ───────────────────────────────────────
    rejection_reason:        str                  # set when KYC or fraud fails
    needs_human_review:      bool                 # True → route to human_review node
    pipeline_status:         str                  # "in_progress" | "completed" | "rejected"
