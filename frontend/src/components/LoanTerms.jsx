/**
 * LoanTerms.js — CrediFlow
 * =========================
 * Component 4: proposed loan terms from the Negotiation Agent.
 *
 * Displays:
 *  - Recommended interest rate
 *  - Tenor (months)
 *  - Collateral requirement (colour-coded)
 *  - Decision badge
 *  - Agent notes
 */

import React from "react";

const COLLATERAL_COLOURS = {
  "None":      "bg-green-100 text-green-700",
  "Optional":  "bg-yellow-100 text-yellow-700",
  "Mandatory": "bg-red-100 text-red-700",
};

const DECISION_COLOURS = {
  "Pre-Approved":              "bg-green-100 text-green-700",
  "Approved with Conditions":  "bg-yellow-100 text-yellow-700",
  "Refer to Senior Underwriter": "bg-red-100 text-red-700",
};

export default function LoanTerms({ data }) {
  if (!data) return null;

  const {
    recommended_interest_rate,
    tenor_months,
    collateral_required,
    decision,
    notes,
  } = data;

  const collateralCls = COLLATERAL_COLOURS[collateral_required] || "bg-gray-100 text-gray-700";
  const decisionCls   = DECISION_COLOURS[decision]              || "bg-indigo-100 text-indigo-700";

  return (
    <div className="bg-white rounded-2xl shadow-md p-8 border border-indigo-100">
      <h2 className="text-xl font-bold text-indigo-700 mb-1">4 — Proposed Loan Terms</h2>
      <p className="text-sm text-gray-500 mb-6">
        Generated by the rule-based Negotiation Agent (v1).
        Future: RL agent trained on historical acceptance outcomes.
      </p>

      {/* Decision badge */}
      <div className="mb-6">
        <span className={`inline-block px-4 py-2 rounded-full font-bold text-sm ${decisionCls}`}>
          Decision: {decision}
        </span>
      </div>

      {/* Terms grid */}
      <div className="grid grid-cols-1 sm:grid-cols-3 gap-4 mb-6">
        {/* Interest rate */}
        <div className="bg-indigo-50 rounded-xl p-5 text-center">
          <p className="text-xs text-indigo-400 uppercase font-semibold mb-1">Interest Rate</p>
          <p className="text-3xl font-extrabold text-indigo-700">
            {recommended_interest_rate}%
          </p>
          <p className="text-xs text-gray-400 mt-1">per annum</p>
        </div>

        {/* Tenor */}
        <div className="bg-indigo-50 rounded-xl p-5 text-center">
          <p className="text-xs text-indigo-400 uppercase font-semibold mb-1">Tenor</p>
          <p className="text-3xl font-extrabold text-indigo-700">{tenor_months}</p>
          <p className="text-xs text-gray-400 mt-1">months</p>
        </div>

        {/* Collateral */}
        <div className={`rounded-xl p-5 text-center ${collateralCls}`}>
          <p className="text-xs uppercase font-semibold mb-1 opacity-70">Collateral</p>
          <p className="text-xl font-extrabold">{collateral_required}</p>
          <p className="text-xs mt-1 opacity-60">requirement</p>
        </div>
      </div>

      {/* Notes */}
      {notes && (
        <div className="bg-gray-50 border border-gray-200 rounded-xl p-4 text-sm text-gray-600">
          <strong className="text-indigo-600">Agent Note: </strong>{notes}
        </div>
      )}
    </div>
  );
}
